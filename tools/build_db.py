#!/usr/bin/env python3
"""Build data/mobdb.lua for Tidy from CatsEyeXI server SQL.
Author: Guabancex

usage: build_db.py <catseyexi sql dir> <out lua file>

Reads mob_spawn_points, mob_groups, mob_droplist, item_basic, item_mods (+
zone_settings for zone names) and writes, as Lua tables:
  zones[zone]  = { [mob index] = dropid }     mob id = 0x1000000 + zone<<12 + index
  names[zone]  = { [lowercase client name] = { dropid, ... } }
  drops[dropid]= { item1, rate1, item2, rate2, ... }   kill drops only (types 0/1)
                 rate is per mille; for a grouped row it's the item's weight
                 inside its group
  dgroup[dropid]= { group of row 1, group of row 2, ... }  (only lists with groups;
                 0 = not grouped)
  grate[dropid] = { [group] = group rate per mille }
  th_gear[item] = Treasure Hunter the item adds (item_mods, mod 303)
  items[item]  = { npc_sell_gil, flags }      flags: 1 = Rare, 2 = Ex
                 (every dropped item, plus any item with a sell price or Rare/Ex)
  zone_names[zone] = 'Name'
"""
import re, sys, os

src, out = sys.argv[1], sys.argv[2]
VARS = {}

def rows(fname):
    path = os.path.join(src, fname)
    if not os.path.exists(path):
        return
    for line in open(path, encoding='utf-8', errors='replace'):
        m = re.match(r"SET @(\w+)\s*=\s*(-?\d+)", line)
        if m:
            VARS[m.group(1)] = int(m.group(2))
            continue
        m = re.match(r"INSERT INTO `\w+` VALUES \((.*)\);", line)
        if not m:
            continue
        vals, cur, q = [], '', False
        for ch in m.group(1):
            if ch == "'" and not (cur.endswith('\\')):
                q = not q
                continue
            if ch == ',' and not q:
                vals.append(cur.strip()); cur = ''
                continue
            cur += ch
        vals.append(cur.strip())
        yield vals

def num(v):
    v = v.strip()
    if v.startswith('@'):
        return VARS.get(v[1:], 0)
    try:
        return int(float(v))
    except ValueError:
        return 0

groups = {}   # (zone, groupid) -> dropid
for v in rows('mob_groups.sql'):
    groups[(num(v[2]), num(v[0]))] = num(v[6])

zones, names = {}, {}
for v in rows('mob_spawn_points.sql'):
    mobid, groupid = num(v[0]), num(v[4])
    zone, index = (mobid >> 12) & 0xFFF, mobid & 0xFFF
    dropid = groups.get((zone, groupid), 0)
    if dropid == 0:
        continue
    zones.setdefault(zone, {})[index] = dropid
    cname = (v[3] or v[2]).replace('_', ' ').strip().lower()
    if cname:
        names.setdefault(zone, {}).setdefault(cname, set()).add(dropid)

used = set()
for z in zones.values():
    used.update(z.values())
drops, dgroup, grate = {}, {}, {}
seen_rows = set()
for v in rows('mob_droplist.sql'):
    dropid, dtype, group, group_rate, item, rate = num(v[0]), num(v[1]), num(v[2]), num(v[3]), num(v[4]), num(v[5])
    if dropid in used and dtype in (0, 1) and item:
        if (dropid, group, item) in seen_rows:
            continue
        seen_rows.add((dropid, group, item))
        lst = drops.setdefault(dropid, [])
        lst += [item, rate]
        dgroup.setdefault(dropid, []).append(group)
        if group:
            grate.setdefault(dropid, {})[group] = group_rate
dgroup = {d: g for d, g in dgroup.items() if any(g)}

wanted_items = set()
for lst in drops.values():
    wanted_items.update(lst[0::2])
items = {}
for v in rows('item_basic.sql'):
    iid = num(v[0])
    f = num(v[6])
    flags = (1 if f & 0x8000 else 0) | (2 if f & 0x4000 else 0)
    sell = num(v[8])
    # Every drop-list item, plus any other item worth something or Rare/Ex, so
    # Extra drops (loot the server adds outside the drop lists) get the same
    # keep rules.
    if iid in wanted_items or sell > 0 or flags:
        items[iid] = (sell, flags)

TREASURE_HUNTER = 303
th_gear = {}
for v in rows('item_mods.sql'):
    if num(v[1]) == TREASURE_HUNTER and num(v[2]) > 0:
        th_gear[num(v[0])] = num(v[2])

zone_names = {}
for v in rows('zone_settings.sql'):
    try:
        zid = num(v[0])
    except Exception:
        continue
    for cand in v[1:6]:
        if re.match(r"^[A-Za-z][A-Za-z0-9_'\-]+$", cand or '') and not cand.isdigit():
            zone_names[zid] = cand.replace('_', ' ')
            break

def lstr(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

with open(out, 'w', encoding='utf-8') as f:
    f.write('-- Generated by tools/build_db.py from CatsEyeXI SQL. Do not edit.\n')
    f.write('local zones, names, drops, items, zone_names = {}, {}, {}, {}, {}\n')
    f.write('local dgroup, grate, th_gear = {}, {}, {}\n')
    for z in sorted(zones):
        idx = zones[z]
        f.write('zones[%d]={' % z + ','.join('[%d]=%d' % (i, idx[i]) for i in sorted(idx)) + '}\n')
    for z in sorted(names):
        f.write('names[%d]={' % z + ','.join('[%s]={%s}' % (lstr(n), ','.join(map(str, sorted(d))))
                                             for n, d in sorted(names[z].items())) + '}\n')
    for d in sorted(drops):
        f.write('drops[%d]={%s}\n' % (d, ','.join(map(str, drops[d]))))
    for d in sorted(dgroup):
        f.write('dgroup[%d]={%s}\n' % (d, ','.join(map(str, dgroup[d]))))
    for d in sorted(grate):
        f.write('grate[%d]={%s}\n' % (d, ','.join('[%d]=%d' % (g, grate[d][g]) for g in sorted(grate[d]))))
    f.write('th_gear={' + ','.join('[%d]=%d' % (i, th_gear[i]) for i in sorted(th_gear)) + '}\n')
    f.write('items={' + ','.join('[%d]={%d,%d}' % (i, items[i][0], items[i][1]) for i in sorted(items)) + '}\n')
    f.write('zone_names={' + ','.join('[%d]=%s' % (z, lstr(n)) for z, n in sorted(zone_names.items())) + '}\n')
    f.write('return { zones = zones, names = names, drops = drops, items = items, zone_names = zone_names,\n'
            '         dgroup = dgroup, grate = grate, th_gear = th_gear }\n')

print('mobs %d, zones %d, droplists %d (%d with groups), items %d, TH gear %d, zone names %d' % (
    sum(len(z) for z in zones.values()), len(zones), len(drops), len(dgroup), len(items), len(th_gear), len(zone_names)))
